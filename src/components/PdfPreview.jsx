import { useEffect, useMemo, useState } from 'react'
import StarBorder from './StarBorder.jsx'

export default function PdfPreview({ blob, filename, onDownload, onClear, title = 'Preview' }) {
  const [url, setUrl] = useState('')

  const hasBlob = Boolean(blob)
  const displayName = typeof filename === 'string' && filename.length > 0 ? filename : ''

  const safeTitle = useMemo(() => {
    const base = String(title || 'Preview')
    return base.length > 120 ? `${base.slice(0, 120)}…` : base
  }, [title])

  useEffect(() => {
    if (!blob) {
      setUrl('')
      return
    }

    const nextUrl = URL.createObjectURL(blob)
    setUrl(nextUrl)

    return () => {
      URL.revokeObjectURL(nextUrl)
    }
  }, [blob])

  const canDownload = hasBlob && typeof onDownload === 'function'
  const canClear = typeof onClear === 'function'

  return (
    <section className="panel stack">
      <div className="row toolActionsRow" style={{ flexWrap: 'wrap' }}>
        <div className="muted" style={{ fontWeight: 800 }}>
          {safeTitle}
        </div>

        <div className="row" style={{ gap: 10, flexWrap: 'wrap' }}>
          <StarBorder
            as="button"
            className="primaryBtn"
            color="var(--accent)"
            speed="5s"
            onClick={onDownload}
            disabled={!canDownload}
            type="button"
          >
            Download PDF
          </StarBorder>

          {canClear ? (
            <button className="dangerBtn" type="button" onClick={onClear} disabled={!hasBlob && !displayName}>
              Clear
            </button>
          ) : null}
        </div>
      </div>

      <div className="muted">{displayName || 'No preview yet'}</div>

      {hasBlob && url ? (
        <iframe className="pdfPreviewFrame" src={url} title={safeTitle} loading="lazy" />
      ) : (
        <div
          className="muted"
          style={{
            border: '1px dashed rgba(255,255,255,0.14)',
            borderRadius: 14,
            padding: 16,
            minHeight: 180,
            display: 'grid',
            placeItems: 'center',
          }}
        >
          Run the tool to generate a PDF preview.
        </div>
      )}
    </section>
  )
}






















































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































































